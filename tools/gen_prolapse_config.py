#!/usr/bin/env python3
"""Generate payloads/prolapse/include/prolapse_config.h from the ledger.

The ledger is docs/PROLAPSE_OFFSETS.md.  The generated header is deliberately
just a string table: the payload parses numbers at the point of use, so a
ledger row that still says "port pending" cannot silently become a guessed
integer.

Usage:
  python3 tools/gen_prolapse_config.py            # write the header
  python3 tools/gen_prolapse_config.py --check    # fail on drift
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
LEDGER = ROOT / "docs" / "PROLAPSE_OFFSETS.md"
OUT = ROOT / "payloads" / "prolapse" / "include" / "prolapse_config.h"


def cells(line: str) -> list[str]:
    return [c.strip().strip("`") for c in line.strip().strip("|").split("|")]


def clean(value: str) -> str:
    return value.replace("**", "").strip().strip("`").strip()


def parse_ledger(text: str) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    section = None
    for line in text.splitlines():
        if line.startswith("## "):
            if line.startswith("## Runtime keys"):
                section = "runtime"
            elif line.startswith("## Kernel/object values"):
                section = "kernel"
            else:
                section = None
            continue
        if section is None or not line.startswith("|"):
            continue
        c = cells(line)
        if len(c) < 4 or c[0] in {"Key", "Arithmetic"} or c[0].startswith("---"):
            continue
        key = clean(c[0])
        if not key or " " in key:
            continue
        if section == "runtime":
            value_1400 = clean(c[1])
            value_1410 = value_1400
            phase = clean(c[3]) if len(c) > 3 else "all"
        else:
            value_1400 = clean(c[1])
            value_1410 = clean(c[2])
            phase = clean(c[3]) if len(c) > 3 else "all"
        rows.append({
            "key": key,
            "value_1400": value_1400,
            "value_1410": value_1410,
            "phase": phase,
        })
    return rows


def cstr(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(rows: list[dict[str, str]]) -> str:
    out = [
        "/* Generated by tools/gen_prolapse_config.py from docs/PROLAPSE_OFFSETS.md.",
        " * Do not edit by hand. */",
        "#pragma once",
        "",
        "typedef struct prolapse_ledger_entry {",
        "    const char *key;",
        "    const char *value_1400;",
        "    const char *value_1410;",
        "    const char *phase;",
        "} prolapse_ledger_entry_t;",
        "",
        "static const prolapse_ledger_entry_t g_prolapse_ledger[] = {",
    ]
    for row in rows:
        out.append(
            "    {%s, %s, %s, %s},"
            % (cstr(row["key"]), cstr(row["value_1400"]),
               cstr(row["value_1410"]), cstr(row["phase"]))
        )
    out.extend([
        "};",
        "",
        "static const unsigned g_prolapse_ledger_count =",
        "    (unsigned)(sizeof(g_prolapse_ledger) / sizeof(g_prolapse_ledger[0]));",
        "",
    ])
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = parse_ledger(LEDGER.read_text(encoding="utf-8"))
    if len(rows) < 20:
        print("ledger parse produced too few rows", file=sys.stderr)
        return 2
    body = render(rows)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != body:
            print(f"{OUT} is stale; run tools/gen_prolapse_config.py", file=sys.stderr)
            return 1
        print(f"{OUT}: up to date ({len(rows)} rows)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
